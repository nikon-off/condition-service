-- ============================================================================
-- V4: Добавление хеша содержимого условия (content_hash) в таблицу conditions.
--
-- Назначение: детерминированный хеш исходного представления условия (например,
-- сырой XML-настройки 1С DCS — поле xmlPayload у ConditionImportDto). Позволяет:
--   * обнаруживать дубликаты при импорте (уникальный индекс);
--   * определять изменение содержания условия без сравнения больших строк.
--
-- Формат: SHA-256 в hex-представлении -> ровно 64 символа (VARCHAR(64)).
--
-- Колонка оставлена nullable: существующие строки (seed-данные V3) не имеют
-- исходного содержимого для хеширования. PostgreSQL допускает несколько NULL
-- в уникальном индексе, поэтому конфликтов между ещё не хешированными строками нет.
-- ============================================================================

ALTER TABLE conditions
    ADD COLUMN content_hash VARCHAR(64);

-- Уникальный индекс для поиска дубликатов и быстрого upsert по хешу при импорте.
CREATE UNIQUE INDEX idx_conditions_hash
    ON conditions (content_hash);