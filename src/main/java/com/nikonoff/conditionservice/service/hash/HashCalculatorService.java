package com.nikonoff.conditionservice.service.hash;

/**
 * Сервис расчёта детерминированного SHA-256 хеша содержимого условия.
 *
 * <p>
 * Используется для дедупликации страховых условий: если два разных договора
 * содержат абсолютно одинаковое условие (одинаковый JSON-payload после
 * парсинга),
 * они должны ссылаться на одну и ту же запись в таблице {@code conditions}
 * (см. уникальный индекс {@code idx_conditions_hash} в миграции V4).
 * </p>
 */
public interface HashCalculatorService {

    /**
     * Рассчитывает SHA-256 хеш от JSON-строки.
     *
     * <p>
     * Перед хешированием JSON нормализуется: удаляются лишние пробелы,
     * а ключи (в том числе вложенных объектов) сортируются в алфавитном порядке.
     * Благодаря этому логически эквивалентные документы вида
     * {@code {"b":2,"a":1}} и {@code {"a":1,"b":2}} дают одинаковый хеш.
     * </p>
     *
     * @param jsonPayload строка с JSON (объект, массив или скаляр)
     * @return hex-строка SHA-256 хеша — ровно 64 символа в нижнем регистре
     * @throws IllegalArgumentException если {@code jsonPayload} равен {@code null}
     *                                  или не является корректным JSON
     */
    String calculateHash(String jsonPayload);
}